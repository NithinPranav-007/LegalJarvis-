"""Real DOCX and PDF document export engine for Indian court petitions.

Uses python-docx and reportlab to generate authentic, professionally formatted
legal documents compliant with Indian court presentation standards.
"""

import io
from typing import Any
import docx
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


class NumberedCanvas(canvas.Canvas):
    """Custom two-pass canvas for running header and accurate 'Page X of Y' footer."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count: int):
        self.saveState()
        self.setFont("Times-Roman", 9)
        self.setFillColor(colors.HexColor("#475569"))

        # Running header on pages after page 1
        if self._pageNumber > 1:
            self.drawString(54, 800, "NEEDHI — CITATION-VERIFIED COURT DRAFT")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(54, 794, 540, 794)

        # Running footer on all pages
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(540, 36, page_str)
        self.drawString(
            54,
            36,
            "INFORMATIONAL COURT DRAFT • REQUIRES ADVOCATE VERIFICATION AND SIGNATURE",
        )
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(54, 48, 540, 48)
        self.restoreState()


def export_petition_docx(
    sections: dict[str, str],
    title: str,
    metadata: dict[str, Any] | None = None,
) -> io.BytesIO:
    """Export petition to genuine DOCX with Indian court legal formatting."""
    doc = docx.Document()

    # 1. Page Margins (Standard Indian Legal format: 1.25" left margin, 1.0" right/top/bottom)
    for section in doc.sections:
        section.top_margin = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin = Inches(1.25)
        section.right_margin = Inches(1.0)

    # 2. Disclaimer Header Box
    disclaimer_p = doc.add_paragraph()
    disclaimer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    d_run = disclaimer_p.add_run(
        "*** INFORMATIONAL WORK PRODUCT GENERATED BY NEEDHI ***\n"
        "THIS DRAFT MUST BE INDEPENDENTLY VERIFIED, FINALIZED, AND SIGNED BY A LICENSED ADVOCATE PRIOR TO FILING."
    )
    d_run.font.name = "Times New Roman"
    d_run.font.size = Pt(8.5)
    d_run.font.italic = True
    d_run.font.color.rgb = RGBColor(120, 53, 15)

    doc.add_paragraph()

    # 3. Court Header & Cause Title
    court_header = sections.get("court_header", "")
    if court_header:
        p_ch = doc.add_paragraph()
        p_ch.alignment = WD_ALIGN_PARAGRAPH.CENTER
        ch_run = p_ch.add_run(court_header)
        ch_run.font.name = "Times New Roman"
        ch_run.font.size = Pt(13)
        ch_run.font.bold = True

    cause_title = sections.get("cause_title", "")
    if cause_title:
        # Strip header if already rendered
        ct_clean = cause_title.replace(court_header, "").strip()
        p_ct = doc.add_paragraph()
        p_ct.alignment = WD_ALIGN_PARAGRAPH.CENTER
        ct_run = p_ct.add_run(ct_clean)
        ct_run.font.name = "Times New Roman"
        ct_run.font.size = Pt(11.5)
        ct_run.font.bold = True

    # 4. Standard Document Sections
    section_order = [
        ("synopsis", "SYNOPSIS AND LIST OF DATES"),
        ("nature_of_petition", "MEMORANDUM OF PETITION"),
        ("facts_and_chronology", "STATEMENT OF FACTS"),
        ("questions_of_law", "SUBSTANTIAL QUESTIONS OF LAW"),
        ("grounds", "GROUNDS"),
        ("interim_relief", "INTERIM RELIEF / APPLICATION FOR STAY"),
        ("prayer", "PRAYER"),
        ("verification", "VERIFICATION AFFIDAVIT"),
        ("list_of_annexures", "LIST OF ANNEXURES"),
    ]

    for key, heading_title in section_order:
        content = sections.get(key, "").strip()
        if not content:
            continue

        # Add section heading
        doc.add_page_break() if key in ("synopsis", "verification") else None
        h_p = doc.add_paragraph()
        h_p.paragraph_format.space_before = Pt(14)
        h_p.paragraph_format.space_after = Pt(6)
        h_p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        h_run = h_p.add_run(heading_title)
        h_run.font.name = "Times New Roman"
        h_run.font.size = Pt(12)
        h_run.font.bold = True
        h_run.font.underline = True

        # Render content paragraphs
        paragraphs = content.split("\n\n")
        for para in paragraphs:
            para_clean = para.strip()
            if not para_clean:
                continue

            p = doc.add_paragraph()
            p.paragraph_format.line_spacing = 1.35
            p.paragraph_format.space_after = Pt(6)
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

            # Bold prefix for numbered paragraphs or Ground titles
            if para_clean.startswith("GROUND ") or para_clean.startswith("PRAYER:") or para_clean.startswith("VERIFICATION:"):
                r = p.add_run(para_clean)
                r.font.bold = True
            else:
                r = p.add_run(para_clean)

            r.font.name = "Times New Roman"
            r.font.size = Pt(11)

    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer


def export_petition_pdf(
    sections: dict[str, str],
    title: str,
    metadata: dict[str, Any] | None = None,
) -> io.BytesIO:
    """Export petition to genuine formatted PDF using reportlab."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom legal styling
    style_court_title = ParagraphStyle(
        "CourtTitle",
        fontName="Times-Bold",
        fontSize=12.5,
        leading=16,
        alignment=1,  # Center
        textColor=colors.HexColor("#071e17"),
        spaceAfter=8,
    )

    style_cause_title = ParagraphStyle(
        "CauseTitle",
        fontName="Times-Bold",
        fontSize=10.5,
        leading=14,
        alignment=1,  # Center
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=12,
    )

    style_heading = ParagraphStyle(
        "LegalHeading",
        fontName="Times-Bold",
        fontSize=11.5,
        leading=15,
        alignment=0,  # Left
        textColor=colors.HexColor("#071e17"),
        spaceBefore=14,
        spaceAfter=6,
    )

    style_body = ParagraphStyle(
        "LegalBody",
        fontName="Times-Roman",
        fontSize=10,
        leading=14.5,
        alignment=4,  # Justified
        textColor=colors.HexColor("#020617"),
        spaceAfter=6,
    )

    style_disclaimer = ParagraphStyle(
        "Disclaimer",
        fontName="Times-Italic",
        fontSize=8,
        leading=11,
        alignment=1,
        textColor=colors.HexColor("#78350f"),
    )

    story = []

    # 1. Top Legal Disclaimer Notice Banner
    disclaimer_text = (
        "<b>NEEDHI AI-GENERATED PETITION DRAFT</b><br/>"
        "FOR INFORMATIONAL RESEARCH PURPOSES ONLY • MUST BE REVIEWED, VERIFIED, AND SIGNED BY A LICENSED ADVOCATE BEFORE COURT FILING."
    )
    disclaimer_table = Table([[Paragraph(disclaimer_text, style_disclaimer)]], colWidths=[485])
    disclaimer_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#faeae1")),
                ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#f3d3be")),
                ("PADDING", (0, 0), (-1, -1), 6),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ]
        )
    )
    story.append(disclaimer_table)
    story.append(Spacer(1, 14))

    # 2. Court Heading
    court_header = sections.get("court_header", "")
    if court_header:
        for line in court_header.split("\n"):
            if line.strip():
                story.append(Paragraph(line.strip(), style_court_title))
        story.append(Spacer(1, 6))

    # 3. Cause Title
    cause_title = sections.get("cause_title", "")
    if cause_title:
        ct_clean = cause_title.replace(court_header, "").strip()
        for line in ct_clean.split("\n"):
            line_str = line.strip()
            if line_str:
                story.append(Paragraph(line_str, style_cause_title))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=10))

    # 4. Standard Document Sections
    section_order = [
        ("synopsis", "SYNOPSIS AND LIST OF DATES"),
        ("nature_of_petition", "MEMORANDUM OF PETITION"),
        ("facts_and_chronology", "STATEMENT OF FACTS"),
        ("questions_of_law", "SUBSTANTIAL QUESTIONS OF LAW"),
        ("grounds", "GROUNDS"),
        ("interim_relief", "INTERIM RELIEF / APPLICATION FOR STAY"),
        ("prayer", "PRAYER"),
        ("verification", "VERIFICATION AFFIDAVIT"),
        ("list_of_annexures", "LIST OF ANNEXURES"),
    ]

    for key, heading_title in section_order:
        content = sections.get(key, "").strip()
        if not content:
            continue

        story.append(Paragraph(f"<u>{heading_title}</u>", style_heading))

        paragraphs = content.split("\n\n")
        for para in paragraphs:
            para_clean = para.strip().replace("\n", "<br/>")
            if not para_clean:
                continue
            story.append(Paragraph(para_clean, style_body))

        story.append(Spacer(1, 8))

    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer
