"""Statute concordance tool and review workflow (Task T-15 / FR-13 / Rule 3).

STRICT RULE 3: Concordance rows must NEVER be generated by LLM recall.
Every concordance entry must carry an official Gazette or Parliamentary
committee comparative table source URL and legal reviewer initials.
If no verified mapping is available, the concordance table remains empty
and the system explicitly informs the user that a verified mapping is not yet available.
"""

import datetime
from typing import Any

from pydantic import BaseModel, Field, HttpUrl
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.db.models import Statute, StatuteConcordance, StatuteSection, StatuteVersion


class ConcordanceImportSchema(BaseModel):
    old_statute_code: str = Field(..., description="Repealed statute code, e.g. IPC, CrPC")
    old_section_no: str = Field(..., description="Section number in repealed code, e.g. 302")
    new_statute_code: str = Field(..., description="Replacing statute code, e.g. BNS, BNSS")
    new_section_no: str = Field(..., description="Section number in replacing code, e.g. 103")
    source_url: HttpUrl = Field(
        ...,
        description="Official Gazette of India, Parliamentary Committee, or MHA Comparative Table URL",
    )
    reviewed_by: str = Field(
        ...,
        min_length=2,
        max_length=64,
        description="Legal reviewer initials / identity certifying concordance accuracy",
    )
    reviewed_at: datetime.date = Field(
        default_factory=datetime.date.today,
        description="Date of reviewer certification",
    )
    note: str | None = Field(
        default=None,
        max_length=1000,
        description="Substantive changes between old and new provisions (e.g. added sub-clauses, altered punishment)",
    )


def import_concordance_entry(
    db: Session,
    entry: ConcordanceImportSchema,
) -> StatuteConcordance:
    """Import a reviewer-signed concordance mapping into the database.

    Enforces Rule 3: Validates both source_url and reviewed_by, and verifies
    both sections exist in the database.
    """
    if not str(entry.source_url).strip():
        raise ValueError(
            "Rule 3 Violation: source_url is strictly mandatory for statute concordance."
        )
    if not entry.reviewed_by.strip():
        raise ValueError(
            "Rule 3 Violation: reviewed_by legal reviewer initials are strictly mandatory."
        )

    # Find old section
    old_sec = (
        db.execute(
            select(StatuteSection)
            .join(StatuteVersion, StatuteSection.version_id == StatuteVersion.id)
            .join(Statute, StatuteVersion.statute_id == Statute.id)
            .where(
                func.upper(Statute.short_name) == entry.old_statute_code.upper().strip(),
                StatuteSection.section_no == entry.old_section_no.strip(),
            )
        )
        .scalars()
        .first()
    )
    if not old_sec:
        raise ValueError(
            f"Old section {entry.old_statute_code} {entry.old_section_no} does not exist in statute_sections."
        )

    # Find new section
    new_sec = (
        db.execute(
            select(StatuteSection)
            .join(StatuteVersion, StatuteSection.version_id == StatuteVersion.id)
            .join(Statute, StatuteVersion.statute_id == Statute.id)
            .where(
                func.upper(Statute.short_name) == entry.new_statute_code.upper().strip(),
                StatuteSection.section_no == entry.new_section_no.strip(),
            )
        )
        .scalars()
        .first()
    )
    if not new_sec:
        raise ValueError(
            f"New section {entry.new_statute_code} {entry.new_section_no} does not exist in statute_sections."
        )

    # Check if existing concordance row exists
    existing = db.execute(
        select(StatuteConcordance).where(
            StatuteConcordance.old_section_id == old_sec.id,
            StatuteConcordance.new_section_id == new_sec.id,
        )
    ).scalar_one_or_none()

    if existing:
        existing.source_url = str(entry.source_url)
        existing.reviewed_by = entry.reviewed_by
        existing.reviewed_at = entry.reviewed_at
        existing.note = entry.note
        db.commit()
        db.refresh(existing)
        return existing

    record = StatuteConcordance(
        old_section_id=old_sec.id,
        new_section_id=new_sec.id,
        source_url=str(entry.source_url),
        reviewed_by=entry.reviewed_by,
        reviewed_at=entry.reviewed_at,
        note=entry.note,
    )
    db.add(record)
    db.commit()
    db.refresh(record)
    return record


def lookup_concordance(
    db: Session,
    statute_code: str,
    section_no: str,
) -> dict[str, Any]:
    """Look up verified replacing provision for a repealed statute provision.

    Returns verified=False with explicit honest message if no reviewer-certified
    mapping exists in the database.
    """
    clean_code = statute_code.upper().strip()
    clean_sec = section_no.strip()

    # Query concordance table
    stmt = (
        select(StatuteConcordance, StatuteSection)
        .join(StatuteSection, StatuteConcordance.new_section_id == StatuteSection.id)
        .join(StatuteVersion, StatuteSection.version_id == StatuteVersion.id)
        .join(Statute, StatuteVersion.statute_id == Statute.id)
        .where(
            StatuteConcordance.old_section_id.in_(
                select(StatuteSection.id)
                .join(StatuteVersion, StatuteSection.version_id == StatuteVersion.id)
                .join(Statute, StatuteVersion.statute_id == Statute.id)
                .where(
                    func.upper(Statute.short_name) == clean_code,
                    StatuteSection.section_no == clean_sec,
                )
            )
        )
    )

    result = db.execute(stmt).first()
    if not result:
        return {
            "verified": False,
            "searched_statute": clean_code,
            "searched_section": clean_sec,
            "replacing_provision": None,
            "message": (
                f"No verified concordance mapping has been officially certified by a legal reviewer "
                f"for {clean_code} Section {clean_sec}. Under Rule 3, LegalJarvis does not guess or invent mappings."
            ),
        }

    concordance, new_section = result
    # Find new statute code
    new_version = db.execute(
        select(StatuteVersion).where(StatuteVersion.id == new_section.version_id)
    ).scalar_one()
    new_statute = db.execute(
        select(Statute).where(Statute.id == new_version.statute_id)
    ).scalar_one()

    return {
        "verified": True,
        "searched_statute": clean_code,
        "searched_section": clean_sec,
        "replacing_provision": {
            "statute_code": new_statute.short_name,
            "act_year": new_statute.act_year,
            "section_no": new_section.section_no,
            "heading": new_section.heading,
            "text": new_section.text,
        },
        "source_url": concordance.source_url,
        "reviewed_by": concordance.reviewed_by,
        "reviewed_at": concordance.reviewed_at.isoformat(),
        "note": concordance.note,
    }
